async function loadArtifact(text) {
  const { code } = await transform(text, { loader: "ts", format: "esm" });
  return import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);
}

export async function renderTasksV2Abi(text) {
  const artifact = await loadArtifact(text);
  const digests = Object.fromEntries(
    [...text.matchAll(/\/\/ (\w+)\.json sha256: ([0-9a-f]{64})\s+export const (\w+) =/gu)].map(
      (match) => [match[3], `${match[1]}.json sha256: ${match[2]}`],
    ),
  );
  const missing = [];
  const blocks = [];
  for (const [name, wanted] of Object.entries(TASKS_V2_ABI_SELECTION)) {
    const abi = artifact[name];
    if (!Array.isArray(abi)) {
      missing.push(name);
      continue;
    }
    const entries = [];
    for (const item of wanted) {
      const found = abi.filter(
        (entry) => (entry.type === "function" || entry.type === "event") && entry.name === item,
      );
      if (!found.length) missing.push(`${name}.${item}`);
      entries.push(...found);
    }
    blocks.push(
      `// ${digests[name] ?? "sha256 unavailable"}\nexport const ${name} = ${JSON.stringify(entries)} as const;`,
    );
  }
  if (missing.length) throw new Error(`The vapi-app artifact no longer has: ${missing.join(", ")}`);
  const sha = createHash("sha256").update(text).digest("hex");
  const body = [
    "// SPDX-License-Identifier: Apache-2.0",
    `// Generated by scripts/sync-tasks-v2-abi.mjs from vAPI-Network/vapi-app ${source}`,
    `// (sha256 ${sha}). Do not edit. Refresh: node scripts/sync-tasks-v2-abi.mjs <vapi-app checkout>.`,
    "// Read-only calls and decoding only: never use these to build participant calldata.",
    "",
    ...blocks,
    "",
  ].join("\n");
  return prettier.format(body, {
    ...((await prettier.resolveConfig(target)) ?? {}),
    filepath: target,
  });
}

async function main(argv) {
  const app = argv.find((value) => !value.startsWith("--"));
  if (!app) {
    console.error("Usage: node scripts/sync-tasks-v2-abi.mjs <vapi-app checkout> [--check]");
    return 2;
  }
  const rendered = await renderTasksV2Abi(await readFile(join(resolve(app), source), "utf8"));
  if (argv.includes("--check")) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== rendered) {
      console.error(`${target} is stale. Run: node scripts/sync-tasks-v2-abi.mjs ${app}`);
      return 1;
    }
    console.log("Tasks V2 ABI copy is current.");
    return 0;
  }
  await writeFile(target, rendered);
  console.log(`Wrote ${target}`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  process.exitCode = await main(process.argv.slice(2));
