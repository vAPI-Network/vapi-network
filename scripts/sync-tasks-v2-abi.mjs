// Copies the Tasks V2 ABI entries the CLI, SDK and MCP read or decode from the
// vapi-app generated artifact. Never edit packages/core/src/tasks/v2-abi.generated.ts by hand.
//
//   node scripts/sync-tasks-v2-abi.mjs <vapi-app checkout>          rewrite the copy
//   node scripts/sync-tasks-v2-abi.mjs <vapi-app checkout> --check  exit 1 if it is stale
//
// A selected entry that disappeared from the artifact fails the sync, so contract
// drift surfaces here instead of at signing time.
